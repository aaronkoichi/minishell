#include "minishell.h"

void	handle_sigint(int sig)
{
	(void)sig;
	if (g_signal == 1)
	{
		g_signal = 2;
		rl_replace_line("", 0);
		rl_done = 1;
		ioctl(1, TIOCSTI, "\n");
	}
	else
	{
		rl_replace_line("", 0);
		ft_putstr_fd("\n", 1);
		rl_on_new_line();
		rl_redisplay();
	}
}

void	configure_signal(void)
{
	struct sigaction	sa;

	sa.sa_handler = handle_sigint;
	sigemptyset(&sa.sa_mask);
	sa.sa_flags = 0;
	sigaction(SIGINT, &sa, NULL);
	sa.sa_handler = SIG_IGN;
	sigaction(SIGQUIT, &sa, NULL);
}
